import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

// The LinkedIn sync procedure is authored as skills/linkedin-sync/SKILL.md and
// travels to the agent inside its schedule's task text. The Worker has no
// filesystem, so the text is snapshotted into a TS module at build time.
const source = readFileSync(new URL("../skills/linkedin-sync/SKILL.md", import.meta.url), "utf8");
const version = source.match(/^version: (\d+)$/m)?.[1];
if (!version) throw new Error("skills/linkedin-sync/SKILL.md must declare an integer version");
const hash = createHash("sha256").update(source).digest("hex");

writeFileSync(
  new URL("../src/server/linkedin-skill.gen.ts", import.meta.url),
  `// Generated by scripts/build-linkedin-skill.mjs. Edit skills/linkedin-sync/SKILL.md.\n` +
    `export const linkedinSyncSkill = ${JSON.stringify({ version, hash, content: source })} as const;\n`,
);
